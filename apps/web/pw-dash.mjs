import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message.slice(0, 200)));
await p.goto('file:///home/claude/out/StepSheet-validate-both.html');
await p.waitForTimeout(2000);
await p.locator('input[type=file]').first().setInputFiles('/home/claude/out/orders.csv');
await p.waitForTimeout(3000);
await p.getByRole('button', { name: 'Visuals' }).first().click();
await p.waitForTimeout(2500);
const btns = (await p.locator('button').allInnerTexts()).map(s => s.replace(/\s+/g,' ').trim()).filter(s => /Executive|Generate|Build/i.test(s));
console.log('AI BUTTONS', btns.slice(0, 10).join(' | '));
const exec = p.getByRole('button', { name: /Standard Executive/i }).first();
if (await exec.count()) await exec.click();
await p.waitForTimeout(5000);
await p.screenshot({ path: '/home/claude/pw/10-dashboard.png' });
const badges = await p.locator('[data-testid^="kpi-trend-badge-"]').allInnerTexts();
console.log('BADGES', badges.map(s=>s.replace(/\s+/g,' ')).join(' || '));
const sents = await p.locator('[data-testid^="kpi-trend-badge-"]').evaluateAll(els => els.map(e => e.getAttribute('data-sentiment')));
console.log('SENTIMENTS', sents.join(','));
const story = await p.locator('[data-testid="ai-data-story"]').allInnerTexts();
console.log('STORY', story.join(' ').replace(/\n+/g,' | '));
const cards = await p.locator('[data-testid^="kpi-lineage-toggle-"]').count();
console.log('INFO BUTTONS', cards, '| definitions', await p.locator('[data-testid="kpi-definitions"]').count());
const first = p.locator('[data-testid^="kpi-lineage-toggle-"]').last();
await first.click();
await p.waitForTimeout(500);
console.log('LINEAGE', (await p.locator('[data-testid^="kpi-lineage-kpi"]').first().innerText()).replace(/\n+/g,' | '));
await p.locator('[data-testid^="kpi-lineage-kpi"]').first().scrollIntoViewIfNeeded();
await p.screenshot({ path: '/home/claude/pw/11-lineage.png' });
console.log('ERRORS', errs.join(' | ') || 'none');
await b.close();
