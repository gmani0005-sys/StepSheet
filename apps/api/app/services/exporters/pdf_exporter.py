class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that computes total page count dynamically
    and draws consistent running headers, footers, page numbers, and optional watermarks.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            header_text = getattr(self, "report_title", "StepSheet Executive Report")
            self.drawString(54, letter[1] - 36, header_text)
            date_text = getattr(self, "report_date", "")
            self.drawRightString(letter[0] - 54, letter[1] - 36, date_text)
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)

        # Running Footer
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 54, 30, page_str)

        conf_notice = getattr(self, "confidentiality_notice", "Generated by StepSheet • Confidential")
        self.drawString(54, 30, conf_notice)

        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 42, letter[0] - 54, 42)

        # Optional Watermark
        watermark = getattr(self, "watermark_text", None)
        if watermark:
            self.saveState()
            self.setFont("Helvetica-Bold", 54)
            self.setFillColor(colors.HexColor("#E2E8F0"))
            self.translate(letter[0] / 2.0, letter[1] / 2.0)
            self.rotate(45)
            self.drawCentredString(0, 0, watermark.upper())
            self.restoreState()

        self.restoreState()


def export_pdf_report_file(
    snapshot: ExportSnapshot,
    output_dir: str,
    preview_row_limit: int = 50,
) -> Tuple[str, int, str]:
    """
    Generates a professional multi-page PDF Executive Deliverable:
      - Header & Footer with project title, timestamp, page numbers, watermark/confidentiality.
      - Page 1: Executive Cover & KPI Overview Cards.
      - Page 2: Transformed Data Sample (first 50 rows) with column types & auto-wrapping.
      - Page 3: Pipeline Transformation Lineage & Step Audit Trail.
      - Page 4: Data Quality & Health Scorecard.

    Returns (absolute_file_path, size_bytes, mime_type).
    """
    clean_name = "".join(c if c.isalnum() or c in ("-", "_") else "_" for c in snapshot.dataset_name)
    filename = f"{clean_name}_report.pdf"
    filepath = os.path.join(output_dir, filename)

    doc = SimpleDocTemplate(
        filepath,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom StepSheet Styles
    primary_color = colors.HexColor("#185C37")
    accent_color = colors.HexColor("#217346")
    slate_dark = colors.HexColor("#0F172A")
    slate_text = colors.HexColor("#334155")
    border_gray = colors.HexColor("#CBD5E1")

    style_title = ParagraphStyle(
        "ReportTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=22,
        leading=26,
        textColor=primary_color,
    )

    style_subtitle = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=11,
        leading=15,
        textColor=slate_text,
    )

    style_h2 = ParagraphStyle(
        "ReportH2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=slate_dark,
        spaceBefore=14,
        spaceAfter=6,
    )

    style_body = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=slate_text,
    )

    style_meta_label = ParagraphStyle(
        "MetaLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#475569"),
    )

    style_meta_val = ParagraphStyle(
        "MetaValue",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=11,
        textColor=slate_dark,
    )

    style_th = ParagraphStyle(
        "TableTh",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.white,
    )

    style_td = ParagraphStyle(
        "TableTd",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=10,
        textColor=slate_dark,
    )

    story = []

    # =========================================================================
    # SECTION 1: COVER & EXECUTIVE OVERVIEW
    # =========================================================================
    story.append(Paragraph("StepSheet Executive Report", style_title))
    story.append(Spacer(1, 4))
    story.append(Paragraph(f"Dataset: <b>{snapshot.dataset_name}</b> • Project: <b>{snapshot.project_name or 'Default'}</b>", style_subtitle))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=2, color=primary_color, spaceBefore=2, spaceAfter=14))

    # KPI Summary Cards (2x2 or 4x1 table)
    q_score = (snapshot.quality_report or {}).get("overall_score", 99.0)
    kpi_data = [
        [
            Paragraph("<b>TOTAL RAW ROWS</b>", style_meta_label),
            Paragraph("<b>TRANSFORMED ROWS</b>", style_meta_label),
            Paragraph("<b>ACTIVE COLUMNS</b>", style_meta_label),
            Paragraph("<b>DATA HEALTH SCORE</b>", style_meta_label),
        ],
        [
            Paragraph(f"<font size=14 color='#185C37'><b>{snapshot.total_raw_rows:,}</b></font>", style_title),
            Paragraph(f"<font size=14 color='#185C37'><b>{snapshot.total_exported_rows:,}</b></font>", style_title),
            Paragraph(f"<font size=14 color='#185C37'><b>{len(snapshot.columns)}</b></font>", style_title),
            Paragraph(f"<font size=14 color='#185C37'><b>{q_score:.1f}%</b></font>", style_title),
        ],
    ]
    t_kpi = Table(kpi_data, colWidths=[125, 125, 125, 129])
    t_kpi.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 1, border_gray),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(t_kpi)
    story.append(Spacer(1, 16))

    # Snapshot Metadata Block
    meta_table_data = [
        [Paragraph("Data As Of", style_meta_label), Paragraph(str(snapshot.data_as_of), style_meta_val), Paragraph("Prepared By", style_meta_label), Paragraph(str(snapshot.author), style_meta_val)],
        [Paragraph("Excluded Columns", style_meta_label), Paragraph(", ".join(snapshot.excluded_columns) if snapshot.excluded_columns else "None", style_meta_val), Paragraph("Applied Steps", style_meta_label), Paragraph(f"{len(snapshot.steps)} transformation step(s)", style_meta_val)],
    ]
    t_meta = Table(meta_table_data, colWidths=[100, 152, 100, 152])
    t_meta.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FFFFFF")),
        ("BOX", (0, 0), (-1, -1), 0.5, border_gray),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(t_meta)
    story.append(Spacer(1, 16))

    # Executive Overview Narrative
    story.append(Paragraph("Executive Overview", style_h2))
    overview_text = (
        f"This deliverable represents the verified output of the <b>{snapshot.dataset_name}</b> data pipeline. "
        f"A total of {snapshot.total_raw_rows:,} raw source records were evaluated through {len(snapshot.steps)} analytical "
        f"transformation step(s), producing a finalized dataset of {snapshot.total_exported_rows:,} records across {len(snapshot.columns)} "
        f"standardized columns. Quality rules achieved an overall data integrity health score of <b>{q_score:.1f}%</b>."
    )
    story.append(Paragraph(overview_text, style_body))
    story.append(Spacer(1, 20))

    # =========================================================================
    # SECTION 2: DATASET SAMPLE (FIRST 50 ROWS)
    # =========================================================================
    story.append(PageBreak())
    story.append(Paragraph("Transformed Data Sample (Top Records)", style_h2))
    story.append(Paragraph(f"Showing sample output preview from the pipeline (first {min(len(snapshot.rows), preview_row_limit)} rows). Full records available in workbook package.", style_body))
    story.append(Spacer(1, 10))

    sample_cols = snapshot.columns[:8]  # Up to 8 columns fit nicely on portrait letter
    sample_rows = snapshot.rows[:preview_row_limit]

    col_w = 504 / max(1, len(sample_cols))
    sample_table_data = [[Paragraph(f"<b>{c}</b>", style_th) for c in sample_cols]]

    for r in sample_rows:
        row_cells = []
        for c in sample_cols:
            val = r.get(c)
            s_val = str(val) if val is not None else ""
            if len(s_val) > 22:
                s_val = s_val[:20] + "…"
            row_cells.append(Paragraph(s_val, style_td))
        sample_table_data.append(row_cells)

    t_sample = Table(sample_table_data, colWidths=[col_w] * len(sample_cols), repeatRows=1)
    t_sample.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), primary_color),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ("BOX", (0, 0), (-1, -1), 0.5, border_gray),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 4),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(t_sample)
    story.append(Spacer(1, 20))

    # =========================================================================
    # SECTION 3: PIPELINE LINEAGE & STEP AUDIT TRAIL
    # =========================================================================
    story.append(PageBreak())
    story.append(Paragraph("Pipeline Lineage & Audit Trail", style_h2))
    story.append(Paragraph("Complete step-by-step audit record of operations applied to transform the raw dataset.", style_body))
    story.append(Spacer(1, 10))

    lineage_headers = [
        Paragraph("<b>#</b>", style_th),
        Paragraph("<b>Step Label</b>", style_th),
        Paragraph("<b>Operation</b>", style_th),
        Paragraph("<b>Target Column</b>", style_th),
        Paragraph("<b>Parameters / Logic</b>", style_th),
    ]
    lineage_rows = [lineage_headers]

    for idx, s in enumerate(snapshot.steps):
        params = getattr(s, "params", {}) or {}
        label = getattr(s, "label", f"Step {idx + 1}")
        stype = getattr(s, "type", "transform")
        target_col = params.get("output_column") or params.get("new_column") or params.get("column") or "-"
        logic_summary = str(params.get("formula") or params.get("expression") or f"{stype} operation")
        if len(logic_summary) > 40:
            logic_summary = logic_summary[:38] + "…"

        lineage_rows.append([
            Paragraph(str(idx + 1), style_td),
            Paragraph(f"<b>{label}</b>", style_td),
            Paragraph(stype.upper(), style_td),
            Paragraph(target_col, style_td),
            Paragraph(logic_summary, style_td),
        ])

    if len(lineage_rows) == 1:
        lineage_rows.append([
            Paragraph("1", style_td),
            Paragraph("Raw Source Load", style_td),
            Paragraph("INGESTION", style_td),
            Paragraph("ALL", style_td),
            Paragraph("Direct import without pipeline transformations", style_td),
        ])

    t_lineage = Table(lineage_rows, colWidths=[24, 130, 90, 110, 150], repeatRows=1)
    t_lineage.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), accent_color),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ("BOX", (0, 0), (-1, -1), 0.5, border_gray),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(t_lineage)
    story.append(Spacer(1, 20))

    # =========================================================================
    # SECTION 4: DATA QUALITY SCORECARD
    # =========================================================================
    story.append(Paragraph("Data Quality & Integrity Scorecard", style_h2))
    q_rep = snapshot.quality_report or {}
    rules = q_rep.get("rules", [])

    q_headers = [
        Paragraph("<b>Rule Name</b>", style_th),
        Paragraph("<b>Target Column</b>", style_th),
        Paragraph("<b>Check Type</b>", style_th),
        Paragraph("<b>Status</b>", style_th),
        Paragraph("<b>Passing / Total</b>", style_th),
        Paragraph("<b>Diagnostics</b>", style_th),
    ]
    q_table_data = [q_headers]

    if rules:
        for r in rules:
            st = str(r.get("status", "pass")).upper()
            status_color = "#166534" if st == "PASS" else "#991B1B" if st == "FAIL" else "#92400E"
            q_table_data.append([
                Paragraph(r.get("rule_name", "Check"), style_td),
                Paragraph(r.get("column", "All"), style_td),
                Paragraph(r.get("rule_type", "type"), style_td),
                Paragraph(f"<font color='{status_color}'><b>{st}</b></font>", style_td),
                Paragraph(f"{r.get('passing_count', 0)} / {len(snapshot.rows)}", style_td),
                Paragraph(r.get("message", "Compliant"), style_td),
            ])
    else:
        # Default Column Completeness Checks
        for c in snapshot.columns[:6]:
            nulls = sum(1 for r in snapshot.rows if r.get(c) is None or str(r.get(c)).strip() == "")
            st = "PASS" if nulls == 0 else "WARN" if nulls < len(snapshot.rows) * 0.1 else "FAIL"
            status_color = "#166534" if st == "PASS" else "#991B1B" if st == "FAIL" else "#92400E"
            q_table_data.append([
                Paragraph(f"NotNull_{c}", style_td),
                Paragraph(c, style_td),
                Paragraph("completeness", style_td),
                Paragraph(f"<font color='{status_color}'><b>{st}</b></font>", style_td),
                Paragraph(f"{len(snapshot.rows) - nulls} / {len(snapshot.rows)}", style_td),
                Paragraph("100% complete" if nulls == 0 else f"{nulls} missing values", style_td),
            ])

    t_qual = Table(q_table_data, colWidths=[100, 80, 75, 55, 75, 119], repeatRows=1)
    t_qual.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E293B")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ("BOX", (0, 0), (-1, -1), 0.5, border_gray),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(t_qual)

    # Attach properties to canvas maker
    def make_canvas(*args, **kwargs):
        c = NumberedCanvas(*args, **kwargs)
        c.report_title = f"{snapshot.project_name or 'StepSheet'} — {snapshot.dataset_name}"
        c.report_date = snapshot.data_as_of
        c.watermark_text = snapshot.watermark
        c.confidentiality_notice = snapshot.confidentiality_notice or "Generated by StepSheet • Confidential"
        return c

    doc.build(story, canvasmaker=make_canvas)

    size_bytes = os.path.getsize(filepath)
    mime_type = "application/pdf"
    return filepath, size_bytes, mime_type
