/**
 * IDS-utilization scenario (timesheet hours vs expected hours, daily/weekly/monthly).
 * Locks in what the large IDS test found: XLSX extracts with report metadata above
 * the header, day/week trends for a one-month run, effort measures and an
 * actual-vs-expected utilisation rate on generated dashboards.
 */
import { describe, it, expect } from 'vitest';
import ExcelJS from 'exceljs';
import { localEngine } from '../api/localEngine';
import { dashItems, dateIntervalFor, cellInPeriod } from '../engine/dashboardData';
import { suggestRatioKpi, kpiValue } from '../engine/kpiInsights';

const fileOf = (name: string, buf: ArrayBuffer | Uint8Array, type: string) => {
  const u8 = buf instanceof Uint8Array ? buf : new Uint8Array(buf);
  return { name, type, size: u8.byteLength, arrayBuffer: async () => u8.buffer.slice(u8.byteOffset, u8.byteOffset + u8.byteLength), text: async () => new TextDecoder().decode(u8) } as any;
};

describe('XLSX extract with report metadata above the header', () => {
  const build = async (metaRows: Array<string[]>, header: string[], data: any[][]) => {
    const wb = new ExcelJS.Workbook();
    const ws = wb.addWorksheet('Sheet1');
    metaRows.forEach((r) => ws.addRow(r));
    ws.addRow(header);
    data.forEach((r) => ws.addRow(r));
    return new Uint8Array(await wb.xlsx.writeBuffer());
  };

  it('finds the real header under 10 metadata rows and keeps every column', async () => {
    const meta = [['TU Position Report'], ['Run date: 2026-11-02'], ['Filter: CM1'], [''], ['Generated by HR'], [''], ['Confidential'], [''], ['Template v3'], ['']];
    const header = ['eID', 'Associate Name', 'Position - Country', 'Position - City', 'Location Weekly Hours', 'IDS % (Whole Number)'];
    const buf = await build(meta, header, [['e1', 'Ana', 'India', 'Chennai', 45, 60], ['e2', 'Bo', 'USA', 'Raleigh', 40, 0]]);
    const ds = await localEngine.uploadDataset(fileOf('tu.xlsx', buf, 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'), 'tu');
    expect(ds.schema_metadata.map((c: any) => c.name)).toEqual(header);
    expect(ds.row_count).toBe(2);
    const rows = (await localEngine.getRows(ds.id, { limit: 5 })).rows;
    expect(rows[0]).toMatchObject({ eID: 'e1', 'Location Weekly Hours': 45, 'IDS % (Whole Number)': 60 });
  });

  it('leaves an ordinary sheet (header on row 1) as it was, and names blank/duplicate headers', async () => {
    const buf = await build([], ['a', '', 'a'], [[1, 2, 3], [4, 5, 6]]);
    const ds = await localEngine.uploadDataset(fileOf('plain.xlsx', buf, 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'), 'plain');
    expect(ds.schema_metadata.map((c: any) => c.name)).toEqual(['a', 'column_2', 'a_2']);
    expect(ds.row_count).toBe(2);
  });
});

describe('Dashboard time axis for a one-month run', () => {
  const october = Array.from({ length: 31 }, (_, i) => ({ d: `2026-10-${String(i + 1).padStart(2, '0')}`, h: i + 1 }));

  it('trends by day when the data spans up to about two months', () => {
    expect(dateIntervalFor(october, 'd')).toBe('day');
    const { items } = dashItems(october, { type: 'line_area', categoryCol: 'd', valueCol: 'h', aggFunc: 'sum' }, [{ name: 'd', data_type: 'date' }]);
    expect(items).toHaveLength(31);
    expect(items[0]).toMatchObject({ category: '2026-10-01', value: 1 });
  });

  it('trends by Monday-start week up to about six months, and cross-filters on the week', () => {
    const rows = [...october, { d: '2026-12-31', h: 100 }];
    expect(dateIntervalFor(rows, 'd')).toBe('week');
    const { items } = dashItems(rows, { type: 'line_area', categoryCol: 'd', valueCol: 'h', aggFunc: 'sum' }, [{ name: 'd', data_type: 'date' }]);
    expect(items[0].category).toBe('Wk 2026-09-28'); // Thu 1 Oct belongs to the week of Mon 28 Sep
    expect(items[1]).toMatchObject({ category: 'Wk 2026-10-05', value: 5 + 6 + 7 + 8 + 9 + 10 + 11 });
    expect(cellInPeriod('2026-10-11', 'Wk 2026-10-05')).toBe(true); // Sunday
    expect(cellInPeriod('2026-10-12', 'Wk 2026-10-05')).toBe(false);
    expect(cellInPeriod('2026-10-12', '2026-10-12')).toBe(true);
  });
});

describe('Generated dashboard on timesheet utilisation data', () => {
  it('pairs actual with expected at the same grain, as a neutral rate', () => {
    const r = suggestRatioKpi(['Expected Per Day', 'Weekly Actual Hours', 'Weekly Expected Hours', 'Weekly IDS %']);
    expect(r).toMatchObject({ numeratorCol: 'Weekly Actual Hours', denominatorCol: 'Weekly Expected Hours', format: 'percent', goodDirection: 'neutral' });
    expect(kpiValue([{ 'Weekly Actual Hours': 27, 'Weekly Expected Hours': 30 }, { 'Weekly Actual Hours': 33, 'Weekly Expected Hours': 30 }], r as any)).toBeCloseTo(1, 10);
  });

  it('leads with actual hours, never totals a percentage or a roster attribute', async () => {
    const rows: any[] = [];
    ['e1', 'e2', 'e3'].forEach((e, i) => {
      for (let d = 1; d <= 28; d++) {
        const wk = new Date(Date.UTC(2026, 9, d)).getUTCDay() % 6 === 0;
        const exp = wk ? 0 : 6;
        const act = wk ? 0 : [6, 4, 7][i];
        rows.push({ eID: e, CM2: ['Platform', 'Data', 'Apps'][i], 'Location Weekly Hours': 40, 'IDS % (Whole Number)': 75, 'Calendar Date': `2026-10-${String(d).padStart(2, '0')}`, 'Daily Actual Hours': act, 'Daily Expected Hours': exp, 'Daily IDS %': exp ? act / exp : '' });
      }
    });
    const res: any = await localEngine.generateAiDashboard('ids-scenario', 'Build me a complete executive dashboard', {
      rows,
      datasetName: 'fact_daily',
      columns: Object.keys(rows[0]).map((n) => ({ name: n, data_type: n === 'Calendar Date' ? 'date' : typeof rows[0][n] === 'number' ? 'float' : 'text' })),
    } as any);
    const kpis = res.plan.kpis;
    const cols = kpis.map((k: any) => `${k.aggFunc}:${k.column}`);
    expect(cols[0]).toBe('sum:Daily Actual Hours');
    expect(cols).toContain('sum:Daily Expected Hours');
    expect(cols.some((c: string) => /%|Location Weekly Hours/.test(c) && c.startsWith('sum'))).toBe(false);
    const util = kpis.find((k: any) => k.kind === 'ratio');
    expect(util).toMatchObject({ title: 'Utilization (Actual ÷ Expected)', numeratorCol: 'Daily Actual Hours', denominatorCol: 'Daily Expected Hours' });
    expect(kpiValue(rows, util)).toBeCloseTo((6 + 4 + 7) / 18, 10);
  });

  it('treats "Monthly ..." figures as measures, not dates (the monthly page had no numbers)', async () => {
    const rows = Array.from({ length: 12 }, (_, i) => ({
      'IDS EID': `e${i}`, Month: 'Oct-2026', CM2: ['Platform', 'Data', 'Apps'][i % 3],
      'Monthly Actual Hours': 100 + i, 'Monthly Expected Hours': 110, 'Monthly IDS %': (100 + i) / 110, 'Downtime Hours': 2,
    }));
    const res: any = await localEngine.generateAiDashboard('ids-monthly', 'Build me a complete executive dashboard', {
      rows, datasetName: 'monthly',
      columns: Object.keys(rows[0]).map((n) => ({ name: n, data_type: typeof (rows[0] as any)[n] === 'number' ? 'float' : 'text' })),
    } as any);
    const kpis = res.plan.kpis.map((k: any) => `${k.aggFunc}:${k.column}`);
    expect(kpis[0]).toBe('sum:Monthly Actual Hours');
    expect(kpis).toContain('sum:Monthly Expected Hours');
    expect(res.plan.kpis.find((k: any) => k.kind === 'ratio')).toMatchObject({ numeratorCol: 'Monthly Actual Hours', denominatorCol: 'Monthly Expected Hours' });
  });
});
